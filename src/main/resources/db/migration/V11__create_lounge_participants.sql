-- V11: Create lounge participant membership records.
-- Lounge-scoped roles are separate from global users.role.
-- The host remains authoritative in dj_lounges.host_user_id.

CREATE TABLE lounge_participants (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                                     lounge_id BIGINT NOT NULL
                                         REFERENCES dj_lounges(id) ON DELETE CASCADE,

                                     user_id BIGINT NOT NULL
                                         REFERENCES users(id) ON DELETE CASCADE,

                                     role VARCHAR(20) NOT NULL DEFAULT 'LISTENER',

                                     joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     left_at TIMESTAMPTZ,

                                     CONSTRAINT chk_lounge_participants_role
                                         CHECK (role IN ('LISTENER', 'CO_DJ')),

                                     CONSTRAINT chk_lounge_participants_leave_time
                                         CHECK (left_at IS NULL OR left_at >= joined_at)
);

-- Prevent duplicate active memberships.
-- Historical rows remain available for leave/rejoin tracking.
CREATE UNIQUE INDEX uq_lounge_participants_active_membership
    ON lounge_participants (lounge_id, user_id)
    WHERE left_at IS NULL;

-- Efficiently list active participants in a lounge.
CREATE INDEX idx_lounge_participants_active_lounge
    ON lounge_participants (lounge_id, joined_at)
    WHERE left_at IS NULL;

-- Efficiently find a user's active lounge memberships.
CREATE INDEX idx_lounge_participants_active_user
    ON lounge_participants (user_id, lounge_id)
    WHERE left_at IS NULL;